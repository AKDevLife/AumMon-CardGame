const VERSION = "3.0.0";

function obj(
  cardId: string,
  name: string,
  nameEn: string,
  archetype: Archetype,
  cost: number,
  atk: number,
  hp: number,
  keywords: readonly Keyword[],
  traits: readonly Trait[],
  passive: Passive | null,
  active: Active | null,
  flavor: string,
): CardDefinition {
  return {
    cardId,
    name,
    nameEn,
    archetype,
    rarity: "normal",
    cost,
    atk,
    hp,
    keywords,
    traits,
    passive,
    active,
    flavor,
    definitionVersion: VERSION,
  };
}

