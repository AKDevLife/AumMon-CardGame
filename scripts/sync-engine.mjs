#!/usr/bin/env node
/**
 * Copies the pure engine sources into supabase/functions/_shared/game-engine so
 * Edge Functions (Deno) can import them. Supabase only mounts/bundles the
 * supabase/ directory. The copy is generated (git-ignored) — never edit it.
 * Run before `supabase functions serve` / `deploy` (pnpm functions:serve does it).
 */
import { cpSync, rmSync, writeFileSync } from "node:fs";

const target = "supabase/functions/_shared/game-engine";
rmSync(target, { recursive: true, force: true });
cpSync("packages/game-engine/src", target, {
  recursive: true,
  filter: (src) => !src.endsWith(".md"),
});
writeFileSync(`${target}/GENERATED.txt`, "Generated by scripts/sync-engine.mjs — do not edit.\n");
console.log(`Synced engine → ${target}`);
